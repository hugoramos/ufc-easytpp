REGIME_TITLES = {'slow': r'Slow decay ($\beta = 0.025$)',
                 'fast': r'Fast decay ($\beta = 0.50$)'}
MARKERS = {'nll': 'o-', 'rmse': 's-'}
YLABELS = {'nll': 'NLL (nats)', 'rmse': r'RMSE ($\Delta t$)'}
HERE = os.path.dirname(os.path.abspath(__file__))


def make_figure(metric, data, out_name):
    x = np.arange(len(FACTORS))
    fig, axes = plt.subplots(1, 2, figsize=(13, 5))
    for ax, regime in zip(axes, ['slow', 'fast']):
        for m in MODELS:
            means = np.array([np.mean(data[regime][f][m]) for f in FACTORS])
            stds = np.array([np.std(data[regime][f][m]) for f in FACTORS])
            ax.plot(x, means, MARKERS[metric], color=COLORS[m], lw=2, ms=7, label=m)
            ax.fill_between(x, means - stds, means + stds, color=COLORS[m], alpha=0.12)
        ax.set_xticks(x)
        ax.set_xticklabels(XLABELS)
        ax.set_xlabel(r'Extrapolation factor ($\alpha$)', fontsize=12)
        ax.set_ylabel(YLABELS[metric], fontsize=12)
        ax.set_title(REGIME_TITLES[regime], fontsize=12, fontweight='bold')
        ax.legend(fontsize=10)
        ax.grid(True, alpha=0.3)
        ax.spines['top'].set_visible(False)
        ax.spines['right'].set_visible(False)
    plt.tight_layout()
    out_path = os.path.join(HERE, out_name)
    fig.savefig(out_path, dpi=150, bbox_inches='tight')
    plt.close(fig)
    print(f'Saved {out_path}')


if __name__ == '__main__':
    make_figure('nll', NLL, 'fig_extrapolation_nll_sintetico.png')
